import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { resolve } from "node:path";

import { makeService } from "@schizomatic/core";
import type { Artifact, Handler, Validator } from "@schizomatic/core";
import { beforeAll, describe, expect, it } from "vitest";

import { ARTIFACT, DECLARATION, build } from "../src";
import type { Output } from "../src";

const fixtures = resolve(import.meta.dirname, "fixtures");
const basicRoot = resolve(fixtures, "basic");
const accessRoot = resolve(fixtures, "access");

/** Imports the built artifact of a fixture. */
const artifactOf = async <S, H extends Record<string, Handler<never>>>(
  root: string,
): Promise<Artifact<S, H>> => {
  const mod = (await import(resolve(root, ".generated", ARTIFACT))) as {
    default: Artifact<S, H>;
  };
  return mod.default;
};

/** Checks the proof file of a fixture against the built declarations with tsc. */
const prove = (root: string): string => {
  const tsc = createRequire(import.meta.url).resolve("typescript/bin/tsc");
  try {
    execFileSync(process.execPath, [tsc, "-p", root], {
      encoding: "utf8",
      stdio: "pipe",
    });
    return "";
  } catch (error) {
    return (error as { stdout?: string }).stdout ?? String(error);
  }
};

let basic: Output;
let access: Output;

beforeAll(async () => {
  basic = await build({ root: basicRoot });
  access = await build({ root: accessRoot });
}, 60_000);

describe("build", () => {
  it("writes the artifact and the declarations", () => {
    expect(basic.files.map((file) => file.path)).toEqual([
      ARTIFACT,
      DECLARATION,
    ]);
    expect(basic.outDir).toBe(resolve(basicRoot, ".generated"));
    for (const file of basic.files) {
      expect(existsSync(resolve(basic.outDir, file.path))).toBe(true);
    }
  });

  it("writes an artifact that imports nothing and holds no extension", () => {
    for (const output of [basic, access]) {
      const code = readFileSync(resolve(output.outDir, ARTIFACT), "utf8");
      expect(code).not.toMatch(/^import /m);
      expect(code).not.toContain("x-schizomatic");
      expect(code).toContain("Generated by @schizomatic/kit");
    }
  });

  it("proves the declarations with tsc", () => {
    expect(prove(basicRoot)).toBe("");
    expect(prove(accessRoot)).toBe("");
  }, 60_000);
});

describe("basic artifact", () => {
  type User = {
    id: string;
    email: string;
    role: "admin" | "member";
    tags: string[];
    age?: number | null;
    name?: string;
  };
  type Log = { actor: User; at: string; order: number[] };
  type Schema = {
    user: Validator<User>;
    page: Validator<{ items: ("admin" | "member")[]; span?: [number, number] }>;
    event: Validator<
      { kind: "created"; user: User } | { kind: "deleted"; at: string }
    >;
    tree: Validator<{ value: number; children: unknown[] }>;
    audit: { log: Validator<Log> };
  };
  type Handlers = { sorted: Handler<Log> };
  let schema: Schema;
  const uuid = "123e4567-e89b-42d3-a456-426614174000";
  const user = { id: uuid, email: "a@b.co", role: "admin" as const };
  const sorted: Handler<Log> = (log) =>
    log.order.every((n, i) => i === 0 || n >= (log.order[i - 1] ?? 0))
      ? undefined
      : { message: "Out of order.", path: ["order"] };

  beforeAll(async () => {
    const artifact = await artifactOf<Schema, Handlers>(basicRoot);
    expect(artifact.id).toBe("basic");
    expect(artifact.checks).toEqual({ "audit/log": "sorted" });
    schema = makeService(artifact, { handlers: { sorted } });
  });

  it("parses a user and fills the default", () => {
    expect(schema.user.parse(user)).toEqual({ ...user, tags: [] });
  });

  it("checks formats, bounds, patterns, uniqueness, and strictness", () => {
    expect(schema.user.check({ ...user, email: "no" })).toBe(false);
    expect(schema.user.check({ ...user, age: 200 })).toBe(false);
    expect(schema.user.check({ ...user, age: null })).toBe(true);
    expect(schema.user.check({ ...user, name: "lower" })).toBe(false);
    expect(schema.user.check({ ...user, tags: ["a", "a"] })).toBe(false);
    expect(schema.user.check({ ...user, tags: ["a", "b", "c", "d"] })).toBe(
      false,
    );
    expect(schema.user.check({ ...user, extra: 1 })).toBe(false);
  });

  it("checks a tuple, a record, a union, and an intersection", () => {
    expect(schema.page.check({ items: ["admin"], span: [1, 2] })).toBe(true);
    expect(schema.page.check({ items: ["admin"], span: [1] })).toBe(false);
    expect(schema.page.check({ items: [], meta: { a: 1.5 } })).toBe(true);
    expect(schema.page.check({ items: [], meta: { a: 1.3 } })).toBe(false);
    expect(schema.page.check({ items: [], mode: "fast" })).toBe(true);
    expect(schema.page.check({ items: [], mode: 0 })).toBe(false);
    expect(schema.page.check({ items: [], both: { a: "x", b: 1 } })).toBe(true);
    expect(schema.page.check({ items: [], both: { a: "x" } })).toBe(false);
  });

  it("checks a union over a file ref", () => {
    expect(schema.event.check({ kind: "created", user })).toBe(true);
    expect(schema.event.check({ kind: "created", user, extra: 1 })).toBe(false);
    expect(
      schema.event.check({ kind: "deleted", at: "2024-01-01T00:00:00Z" }),
    ).toBe(true);
    expect(schema.event.check({ kind: "other" })).toBe(false);
  });

  it("follows a file that refers to itself", () => {
    expect(schema.tree.parse({ value: 1, children: [{ value: 2 }] })).toEqual({
      value: 1,
      children: [{ value: 2, children: [] }],
    });
    expect(schema.tree.check({ value: -1 })).toBe(false);
  });

  it("serves a nested path and runs its handler", () => {
    const log = { actor: user, at: "2024-01-01T00:00:00Z", order: [1, 2] };
    expect(schema.audit.log.check(log)).toBe(true);
    const result = schema.audit.log.inspect({ ...log, order: [2, 1] });
    expect(result.success).toBe(false);
    if (!result.success) {
      expect(result.issues.map((issue) => [issue.message, issue.path])).toEqual(
        [["Out of order.", ["order"]]],
      );
    }
  });
});

describe("access artifact", () => {
  type Bindings = { admin?: unknown; viewer?: unknown; bot?: unknown };
  type Schema = {
    role: Validator<string>;
    mention: Validator<string>;
    bindings: Validator<Bindings>;
    roster: Validator<unknown>;
    priority: Validator<string[]>;
    policy: { full: Validator<unknown>; partial: Validator<unknown> };
  };
  type Handlers = { noSelfGrant: Handler<Bindings> };
  let schema: Schema;
  const noSelfGrant: Handler<Bindings> = (bindings) => {
    for (const [role, grant] of Object.entries(bindings)) {
      if (grant === `<${role}>`) {
        return { message: "A role grants itself.", path: [role] };
      }
    }
    return undefined;
  };
  const alice = { email: "alice@example.com" };
  const key = { key: "k", ttl: "1h" };

  beforeAll(async () => {
    const artifact = await artifactOf<Schema, Handlers>(accessRoot);
    expect(artifact.schemas).toContain("policy/full");
    schema = makeService(artifact, { handlers: { noSelfGrant } });
  });

  it("checks an enum and a pattern", () => {
    expect(schema.role.check("admin")).toBe(true);
    expect(schema.role.check("other")).toBe(false);
    expect(schema.mention.check("<bot>")).toBe(true);
    expect(schema.mention.check("<other>")).toBe(false);
  });

  it("checks each binding by its role and runs the handler", () => {
    expect(schema.bindings.check({ admin: alice, bot: key })).toBe(true);
    expect(schema.bindings.check({ admin: key })).toBe(false);
    expect(schema.bindings.check({ admin: "<viewer>" })).toBe(true);
    expect(schema.bindings.check({ other: alice })).toBe(false);
    const result = schema.bindings.inspect({ admin: "<admin>" });
    expect(result.success).toBe(false);
    if (!result.success) {
      expect(result.issues.map((issue) => [issue.message, issue.path])).toEqual(
        [["A role grants itself.", ["admin"]]],
      );
    }
  });

  it("requires every role in the roster", () => {
    const roster = {
      admin: { kind: "person", grant: alice },
      viewer: { kind: "person", grant: "<admin>" },
      bot: { kind: "service", grant: key },
    };
    expect(schema.roster.check(roster)).toBe(true);
    expect(schema.roster.check({ admin: roster.admin })).toBe(false);
  });

  it("requires the priority to be a permutation of the roles", () => {
    expect(schema.priority.check(["bot", "admin", "viewer"])).toBe(true);
    expect(schema.priority.check(["admin"])).toBe(false);
    expect(schema.priority.check(["admin", "admin", "bot"])).toBe(false);
    expect(schema.priority.check(["admin", "bot", "other"])).toBe(false);
  });

  it("checks the names of the matrix and a partial policy", () => {
    expect(
      schema.policy.partial.check({ matrix: { doc: { admin: alice } } }),
    ).toBe(true);
    expect(
      schema.policy.partial.check({ matrix: { other: { admin: alice } } }),
    ).toBe(false);
    expect(schema.policy.partial.check({ extra: 1 })).toBe(false);
    expect(schema.policy.full.check({ id: "p", name: "P" })).toBe(false);
  });
});
