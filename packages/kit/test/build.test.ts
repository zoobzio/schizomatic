import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { resolve } from "node:path";

import { makeService } from "@schizomatic/core";
import type { Artifact, Handler, Service } from "@schizomatic/core";
import { beforeAll, describe, expect, it } from "vitest";

import { ARTIFACT, CONTRACT, DECLARATION, build } from "../src";
import type { Output } from "../src";

const fixtures = resolve(import.meta.dirname, "fixtures");
const basicRoot = resolve(fixtures, "basic");
const tokensRoot = resolve(fixtures, "tokens");

/** Imports the built artifact of a fixture. */
const artifactOf = async (root: string): Promise<Artifact> => {
  const mod = (await import(resolve(root, ".generated", ARTIFACT))) as {
    default: Artifact;
  };
  return mod.default;
};

/** Checks the proof file of a fixture against the built declarations with tsc. */
const prove = (root: string): string => {
  const tsc = createRequire(import.meta.url).resolve("typescript/bin/tsc");
  try {
    execFileSync(process.execPath, [tsc, "-p", root], {
      encoding: "utf8",
      stdio: "pipe",
    });
    return "";
  } catch (error) {
    return (error as { stdout?: string }).stdout ?? String(error);
  }
};

let basic: Output;
let tokens: Output;

beforeAll(async () => {
  basic = await build({ root: basicRoot });
  tokens = await build({ root: tokensRoot });
}, 60_000);

describe("build", () => {
  it("writes the contract, the artifact, and the declarations", () => {
    expect(basic.files.map((file) => file.path)).toEqual([
      CONTRACT,
      ARTIFACT,
      DECLARATION,
    ]);
    expect(basic.outDir).toBe(resolve(basicRoot, ".generated"));
    for (const file of basic.files) {
      expect(existsSync(resolve(basic.outDir, file.path))).toBe(true);
    }
    expect(
      JSON.parse(readFileSync(resolve(basic.outDir, CONTRACT), "utf8")),
    ).toEqual(basic.contract);
  });

  it("bundles zod into the artifact so it imports nothing", () => {
    for (const output of [basic, tokens]) {
      const code = readFileSync(resolve(output.outDir, ARTIFACT), "utf8");
      expect(code).not.toMatch(/^import /m);
      expect(code).not.toMatch(/from "zod/);
      expect(code).toContain("Generated by @schizomatic/kit");
    }
  });

  it("proves the declarations with tsc", () => {
    expect(prove(basicRoot)).toBe("");
    expect(prove(tokensRoot)).toBe("");
  }, 60_000);
});

describe("basic artifact", () => {
  type Kinds = {
    user: {
      id: string;
      email: string;
      role: "admin" | "member";
      tags: string[];
      age?: number | null;
      name?: string;
    };
    page: {
      items: ("admin" | "member")[];
      span?: [number, number];
      meta?: Record<string, number>;
    };
    event:
      | { kind: "created"; user: Kinds["user"] }
      | { kind: "deleted"; at: string };
    tree: { value: number; children: Kinds["tree"][] };
  };
  let schema: Service<Kinds>;
  const uuid = "123e4567-e89b-42d3-a456-426614174000";
  const user = { id: uuid, email: "a@b.co", role: "admin" as const };

  beforeAll(async () => {
    const artifact = await artifactOf(basicRoot);
    expect(artifact.id).toBe("basic");
    expect(artifact.params).toEqual([]);
    schema = makeService<Kinds>(artifact);
  });

  it("parses a user, fills the default, and strips extra keys", () => {
    expect(schema.parse.user({ ...user, extra: 1 })).toEqual({
      ...user,
      tags: [],
    });
  });

  it("checks formats, bounds, patterns, and uniqueness", () => {
    expect(schema.check.user({ ...user, email: "no" })).toBe(false);
    expect(schema.check.user({ ...user, age: 200 })).toBe(false);
    expect(schema.check.user({ ...user, age: null })).toBe(true);
    expect(schema.check.user({ ...user, name: "lower" })).toBe(false);
    expect(schema.check.user({ ...user, tags: ["a", "a"] })).toBe(false);
    expect(schema.check.user({ ...user, tags: ["a", "b", "c", "d"] })).toBe(
      false,
    );
  });

  it("checks a tuple, a record, a union, and an intersection", () => {
    expect(schema.check.page({ items: ["admin"], span: [1, 2] })).toBe(true);
    expect(schema.check.page({ items: ["admin"], span: [1] })).toBe(false);
    expect(schema.check.page({ items: [], meta: { a: 1.5 } })).toBe(true);
    expect(schema.check.page({ items: [], meta: { a: 1.3 } })).toBe(false);
    expect(schema.check.page({ items: [], mode: "fast" })).toBe(true);
    expect(schema.check.page({ items: [], mode: 0 })).toBe(false);
    expect(schema.check.page({ items: [], both: { a: "x", b: 1 } })).toBe(true);
    expect(schema.check.page({ items: [], both: { a: "x" } })).toBe(false);
  });

  it("checks a discriminated union and a strict object", () => {
    expect(schema.check.event({ kind: "created", user })).toBe(true);
    expect(schema.check.event({ kind: "created", user, extra: 1 })).toBe(false);
    expect(
      schema.check.event({ kind: "deleted", at: "2024-01-01T00:00:00Z" }),
    ).toBe(true);
    expect(schema.check.event({ kind: "other" })).toBe(false);
  });

  it("checks a recursive def", () => {
    expect(schema.parse.tree({ value: 1, children: [{ value: 2 }] })).toEqual({
      value: 1,
      children: [{ value: 2, children: [] }],
    });
    expect(schema.check.tree({ value: -1 })).toBe(false);
  });
});

describe("tokens artifact", () => {
  type Kinds = Record<
    | "token"
    | "reference"
    | "value"
    | "definition"
    | "overrides"
    | "tokens"
    | "modifiers"
    | "input"
    | "order"
    | "theme"
    | "patch",
    unknown
  >;
  let schema: Service<Kinds>;
  const params = {
    tokens: ["primary", "surface", "space"],
    modifiers: ["color", "motion"],
    contexts: { color: ["light", "dark"], motion: ["full", "reduced"] },
    types: { primary: "color", surface: "color", space: "dimension" },
  };
  const acyclic: Handler = (v) => {
    for (const [name, bound] of Object.entries(v as Record<string, unknown>)) {
      if (bound === `{${name}}`) {
        return { message: "A token references itself.", path: [name] };
      }
    }
    return undefined;
  };
  const red = { hex: "#ff0000" };
  const px = { value: 4, unit: "px" };

  beforeAll(async () => {
    const artifact = await artifactOf(tokensRoot);
    expect(artifact.params).toEqual([
      "tokens",
      "modifiers",
      "contexts",
      "types",
    ]);
    expect(artifact.handlers).toEqual(["acyclic"]);
    schema = makeService<Kinds>(artifact, { params, handlers: { acyclic } });
  });

  it("reads a set param as an enum and a sliced member", () => {
    expect(schema.check.token("primary")).toBe(true);
    expect(schema.check.token("other")).toBe(false);
    expect(schema.check.reference("{space}")).toBe(true);
    expect(schema.check.reference("{other}")).toBe(false);
    expect(schema.check.reference("space")).toBe(false);
  });

  it("picks the value by the type of the key and checks a typed reference", () => {
    expect(schema.check.overrides({ primary: red, space: px })).toBe(true);
    expect(schema.check.overrides({ primary: px })).toBe(false);
    expect(schema.check.overrides({ primary: "{surface}" })).toBe(true);
    expect(schema.check.overrides({ primary: "{space}" })).toBe(false);
    expect(schema.check.overrides({ other: red })).toBe(false);
  });

  it("runs the handler and keeps its path", () => {
    const result = schema.inspect.overrides({ primary: "{primary}" });
    expect(result.success).toBe(false);
    if (!result.success) {
      expect(result.issues.map((issue) => [issue.message, issue.path])).toEqual(
        [["A token references itself.", ["primary"]]],
      );
    }
  });

  it("requires every token in the complete map and checks the names", () => {
    const tokens = {
      primary: { $type: "color", $value: red },
      surface: { $type: "color", $value: "{primary}" },
      space: { $type: "dimension", $value: px },
    };
    expect(schema.check.tokens(tokens)).toBe(true);
    expect(schema.check.tokens({ primary: tokens.primary })).toBe(false);
    const result = schema.inspect.tokens({
      ...tokens,
      "bad;name": tokens.primary,
    });
    expect(result.success).toBe(false);
    if (!result.success) {
      expect(result.issues.map((issue) => issue.path[0])).toContain("bad;name");
    }
  });

  it("checks the contexts of each modifier by the enclosing key", () => {
    expect(
      schema.check.modifiers({
        color: { light: {}, dark: { primary: red } },
        motion: { full: {}, reduced: {} },
      }),
    ).toBe(true);
    expect(
      schema.check.modifiers({
        color: { light: {}, dark: {} },
        motion: { full: {}, reduced: {}, extra: {} },
      }),
    ).toBe(false);
    expect(
      schema.check.modifiers({
        color: { light: {} },
        motion: { full: {}, reduced: {} },
      }),
    ).toBe(false);
    expect(schema.check.modifiers({ color: { light: {}, dark: {} } })).toBe(
      false,
    );
    expect(
      schema.check.modifiers({
        color: { light: {}, dark: { primary: px } },
        motion: { full: {}, reduced: {} },
      }),
    ).toBe(false);
  });

  it("checks the input by the enclosing key", () => {
    expect(schema.check.input({ color: "dark", motion: "full" })).toBe(true);
    expect(schema.check.input({ color: "full", motion: "full" })).toBe(false);
    expect(schema.check.input({ color: "dark" })).toBe(false);
  });

  it("requires the order to be a permutation of the modifiers", () => {
    expect(schema.check.order(["motion", "color"])).toBe(true);
    expect(schema.check.order(["color"])).toBe(false);
    expect(schema.check.order(["color", "color", "motion"])).toBe(false);
    expect(schema.check.order(["color", "motion", "other"])).toBe(false);
  });

  it("checks a partial patch with a subset of contexts", () => {
    expect(
      schema.check.patch({ modifiers: { color: { dark: { primary: red } } } }),
    ).toBe(true);
    expect(schema.check.patch({ modifiers: { color: { blue: {} } } })).toBe(
      false,
    );
    expect(
      schema.check.patch({
        tokens: { primary: red },
        order: ["motion", "color"],
      }),
    ).toBe(true);
    expect(schema.check.patch({ extra: 1 })).toBe(false);
  });
});
