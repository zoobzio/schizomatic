import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { resolve } from "node:path";

import { makeService } from "@schizomatic/core";
import type { Artifact, Handler, Service } from "@schizomatic/core";
import { beforeAll, describe, expect, it } from "vitest";

import { ARTIFACT, CONTRACT, DECLARATION, build } from "../src";
import type { Output } from "../src";

const fixtures = resolve(import.meta.dirname, "fixtures");
const basicRoot = resolve(fixtures, "basic");
const accessRoot = resolve(fixtures, "access");

/** Imports the built artifact of a fixture. */
const artifactOf = async (root: string): Promise<Artifact> => {
  const mod = (await import(resolve(root, ".generated", ARTIFACT))) as {
    default: Artifact;
  };
  return mod.default;
};

/** Checks the proof file of a fixture against the built declarations with tsc. */
const prove = (root: string): string => {
  const tsc = createRequire(import.meta.url).resolve("typescript/bin/tsc");
  try {
    execFileSync(process.execPath, [tsc, "-p", root], {
      encoding: "utf8",
      stdio: "pipe",
    });
    return "";
  } catch (error) {
    return (error as { stdout?: string }).stdout ?? String(error);
  }
};

let basic: Output;
let access: Output;

beforeAll(async () => {
  basic = await build({ root: basicRoot });
  access = await build({ root: accessRoot });
}, 60_000);

describe("build", () => {
  it("writes the contract, the artifact, and the declarations", () => {
    expect(basic.files.map((file) => file.path)).toEqual([
      CONTRACT,
      ARTIFACT,
      DECLARATION,
    ]);
    expect(basic.outDir).toBe(resolve(basicRoot, ".generated"));
    for (const file of basic.files) {
      expect(existsSync(resolve(basic.outDir, file.path))).toBe(true);
    }
    expect(
      JSON.parse(readFileSync(resolve(basic.outDir, CONTRACT), "utf8")),
    ).toEqual(basic.contract);
  });

  it("bundles zod into the artifact so it imports nothing", () => {
    for (const output of [basic, access]) {
      const code = readFileSync(resolve(output.outDir, ARTIFACT), "utf8");
      expect(code).not.toMatch(/^import /m);
      expect(code).not.toMatch(/from "zod/);
      expect(code).toContain("Generated by @schizomatic/kit");
    }
  });

  it("proves the declarations with tsc", () => {
    expect(prove(basicRoot)).toBe("");
    expect(prove(accessRoot)).toBe("");
  }, 60_000);
});

describe("basic artifact", () => {
  type Kinds = {
    user: {
      id: string;
      email: string;
      role: "admin" | "member";
      tags: string[];
      age?: number | null;
      name?: string;
    };
    page: {
      items: ("admin" | "member")[];
      span?: [number, number];
      meta?: Record<string, number>;
    };
    event:
      | { kind: "created"; user: Kinds["user"] }
      | { kind: "deleted"; at: string };
    tree: { value: number; children: Kinds["tree"][] };
  };
  let schema: Service<Kinds>;
  const uuid = "123e4567-e89b-42d3-a456-426614174000";
  const user = { id: uuid, email: "a@b.co", role: "admin" as const };

  beforeAll(async () => {
    const artifact = await artifactOf(basicRoot);
    expect(artifact.id).toBe("basic");
    expect(artifact.params).toEqual([]);
    schema = makeService<Kinds>(artifact);
  });

  it("parses a user, fills the default, and strips extra keys", () => {
    expect(schema.parse.user({ ...user, extra: 1 })).toEqual({
      ...user,
      tags: [],
    });
  });

  it("checks formats, bounds, patterns, and uniqueness", () => {
    expect(schema.check.user({ ...user, email: "no" })).toBe(false);
    expect(schema.check.user({ ...user, age: 200 })).toBe(false);
    expect(schema.check.user({ ...user, age: null })).toBe(true);
    expect(schema.check.user({ ...user, name: "lower" })).toBe(false);
    expect(schema.check.user({ ...user, tags: ["a", "a"] })).toBe(false);
    expect(schema.check.user({ ...user, tags: ["a", "b", "c", "d"] })).toBe(
      false,
    );
  });

  it("checks a tuple, a record, a union, and an intersection", () => {
    expect(schema.check.page({ items: ["admin"], span: [1, 2] })).toBe(true);
    expect(schema.check.page({ items: ["admin"], span: [1] })).toBe(false);
    expect(schema.check.page({ items: [], meta: { a: 1.5 } })).toBe(true);
    expect(schema.check.page({ items: [], meta: { a: 1.3 } })).toBe(false);
    expect(schema.check.page({ items: [], mode: "fast" })).toBe(true);
    expect(schema.check.page({ items: [], mode: 0 })).toBe(false);
    expect(schema.check.page({ items: [], both: { a: "x", b: 1 } })).toBe(true);
    expect(schema.check.page({ items: [], both: { a: "x" } })).toBe(false);
  });

  it("checks a discriminated union and a strict object", () => {
    expect(schema.check.event({ kind: "created", user })).toBe(true);
    expect(schema.check.event({ kind: "created", user, extra: 1 })).toBe(false);
    expect(
      schema.check.event({ kind: "deleted", at: "2024-01-01T00:00:00Z" }),
    ).toBe(true);
    expect(schema.check.event({ kind: "other" })).toBe(false);
  });

  it("checks a recursive def", () => {
    expect(schema.parse.tree({ value: 1, children: [{ value: 2 }] })).toEqual({
      value: 1,
      children: [{ value: 2, children: [] }],
    });
    expect(schema.check.tree({ value: -1 })).toBe(false);
  });
});

describe("access artifact", () => {
  type Kinds = Record<
    | "role"
    | "mention"
    | "principal"
    | "assignment"
    | "bindings"
    | "roster"
    | "matrix"
    | "defaults"
    | "priority"
    | "policy"
    | "amendment",
    unknown
  >;
  let schema: Service<Kinds>;
  const params = {
    roles: ["admin", "viewer", "bot"],
    resources: ["doc", "bucket"],
    actions: { doc: ["read", "write"], bucket: ["list", "put"] },
    owner: { admin: "person", viewer: "person", bot: "service" },
  };
  const noSelfGrant: Handler = (v) => {
    for (const [role, grant] of Object.entries(v as Record<string, unknown>)) {
      if (grant === `<${role}>`) {
        return { message: "A role grants itself.", path: [role] };
      }
    }
    return undefined;
  };
  const alice = { email: "alice@example.com" };
  const key = { key: "k", ttl: "1h" };

  beforeAll(async () => {
    const artifact = await artifactOf(accessRoot);
    expect(artifact.params).toEqual(["roles", "resources", "actions", "owner"]);
    expect(artifact.handlers).toEqual(["noSelfGrant"]);
    schema = makeService<Kinds>(artifact, {
      params,
      handlers: { noSelfGrant },
    });
  });

  it("reads a set param as an enum and a sliced member", () => {
    expect(schema.check.role("admin")).toBe(true);
    expect(schema.check.role("other")).toBe(false);
    expect(schema.check.mention("<bot>")).toBe(true);
    expect(schema.check.mention("<other>")).toBe(false);
    expect(schema.check.mention("bot")).toBe(false);
  });

  it("picks the value by the map value of the key and checks a typed member", () => {
    expect(schema.check.bindings({ admin: alice, bot: key })).toBe(true);
    expect(schema.check.bindings({ admin: key })).toBe(false);
    expect(schema.check.bindings({ admin: "<viewer>" })).toBe(true);
    expect(schema.check.bindings({ admin: "<bot>" })).toBe(false);
    expect(schema.check.bindings({ other: alice })).toBe(false);
  });

  it("runs the handler and keeps its path", () => {
    const result = schema.inspect.bindings({ admin: "<admin>" });
    expect(result.success).toBe(false);
    if (!result.success) {
      expect(result.issues.map((issue) => [issue.message, issue.path])).toEqual(
        [["A role grants itself.", ["admin"]]],
      );
    }
  });

  it("requires every role in the roster and checks the names", () => {
    const roster = {
      admin: { kind: "person", grant: alice },
      viewer: { kind: "person", grant: "<admin>" },
      bot: { kind: "service", grant: key },
    };
    expect(schema.check.roster(roster)).toBe(true);
    expect(schema.check.roster({ admin: roster.admin })).toBe(false);
    const result = schema.inspect.roster({
      ...roster,
      "bad;name": roster.admin,
    });
    expect(result.success).toBe(false);
    if (!result.success) {
      expect(result.issues.map((issue) => issue.path[0])).toContain("bad;name");
    }
  });

  it("checks the actions of each resource by the enclosing key", () => {
    const full = {
      doc: { read: {}, write: { admin: alice } },
      bucket: { list: {}, put: {} },
    };
    expect(schema.check.matrix(full)).toBe(true);
    expect(
      schema.check.matrix({
        ...full,
        bucket: { list: {}, put: {}, extra: {} },
      }),
    ).toBe(false);
    expect(schema.check.matrix({ ...full, doc: { read: {} } })).toBe(false);
    expect(schema.check.matrix({ doc: full.doc })).toBe(false);
    expect(
      schema.check.matrix({
        ...full,
        doc: { read: {}, write: { admin: key } },
      }),
    ).toBe(false);
  });

  it("checks the defaults by the enclosing key", () => {
    expect(schema.check.defaults({ doc: "write", bucket: "list" })).toBe(true);
    expect(schema.check.defaults({ doc: "list", bucket: "list" })).toBe(false);
    expect(schema.check.defaults({ doc: "write" })).toBe(false);
  });

  it("requires the priority to be a permutation of the resources", () => {
    expect(schema.check.priority(["bucket", "doc"])).toBe(true);
    expect(schema.check.priority(["doc"])).toBe(false);
    expect(schema.check.priority(["doc", "doc", "bucket"])).toBe(false);
    expect(schema.check.priority(["doc", "bucket", "other"])).toBe(false);
  });

  it("checks a partial amendment with a subset of actions", () => {
    expect(
      schema.check.amendment({ matrix: { doc: { write: { admin: alice } } } }),
    ).toBe(true);
    expect(schema.check.amendment({ matrix: { doc: { delete: {} } } })).toBe(
      false,
    );
    expect(
      schema.check.amendment({
        roster: { admin: alice },
        priority: ["bucket", "doc"],
      }),
    ).toBe(true);
    expect(schema.check.amendment({ extra: 1 })).toBe(false);
  });
});
