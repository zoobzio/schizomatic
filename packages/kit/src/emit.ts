import type { Contract } from "@schizomatic/contract";

import { ARTIFACT, CONTRACT, DECLARATION } from "./constant";
import { declaration } from "./declare";
import type { OutputFile } from "./types";

/** The banner at the top of every emitted module. It names the contract of the module. */
export const banner = (id: string): string =>
  `// Generated by @schizomatic/kit from ${JSON.stringify(id)}. Do not edit by hand.`;

/**
 * Emits every file of a build.
 *
 * - `contract.json` is the contract.
 * - `index.mjs` is the bundled artifact, with zod inlined.
 * - `index.d.mts` is the declaration of the artifact, with the flat types.
 *
 * @param contract - The contract.
 * @param artifact - The bundled artifact, as {@link bundle} returns it.
 */
export const emit = (contract: Contract, artifact: string): OutputFile[] => [
  { path: CONTRACT, contents: `${JSON.stringify(contract, null, 2)}\n` },
  {
    path: ARTIFACT,
    contents: `${banner(contract.id)}\n${artifact.trimEnd()}\n`,
  },
  { path: DECLARATION, contents: declaration(contract) },
];
