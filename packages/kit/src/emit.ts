import { ARTIFACT, DECLARATION } from "./constant";
import { declaration } from "./declare";
import { defsOf } from "./prove";
import type { Loaded, OutputFile } from "./types";

/** The banner at the top of every emitted module. It names the artifact of the module. */
export const banner = (id: string): string =>
  `// Generated by @schizomatic/kit from ${JSON.stringify(id)}. Do not edit by hand.`;

/**
 * Prints the artifact module. The module holds the documents as data and
 * imports nothing. The service builds them with zod at boot.
 *
 * @param loaded - The loaded source.
 */
export const artifact = (loaded: Loaded): string =>
  [
    banner(loaded.id),
    `export const id = ${JSON.stringify(loaded.id)};`,
    `export const schemas = Object.freeze(${JSON.stringify(loaded.schemas)});`,
    `export const checks = Object.freeze(${JSON.stringify(loaded.checks)});`,
    `export const defs = Object.freeze(${JSON.stringify(defsOf(loaded), null, 2)});`,
    "export default { id, schemas, checks, defs };",
    "",
  ].join("\n");

/**
 * Emits every file of a build.
 *
 * - `index.mjs` is the artifact: the documents as data.
 * - `index.d.mts` is the declaration of the artifact, with the types of
 *   every schema and the type of the service.
 *
 * @param loaded - The loaded source.
 */
export const emit = (loaded: Loaded): OutputFile[] => [
  { path: ARTIFACT, contents: artifact(loaded) },
  { path: DECLARATION, contents: declaration(loaded) },
];
